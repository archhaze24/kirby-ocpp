//! The embedded OCPP 2.1 schema tables (see `schemas/ocpp21/README.md`).

use super::schema::{SchemaTable, SendSchemaTable};

/// Expands to the table of embedded schema files: `(action, request json, response json)`.
macro_rules! embedded_schemas {
    ($($action:literal),+ $(,)?) => {
        &[$((
            $action,
            include_str!(concat!("../../schemas/ocpp21/", $action, "Request.json")),
            include_str!(concat!("../../schemas/ocpp21/", $action, "Response.json")),
        )),+]
    };
}

